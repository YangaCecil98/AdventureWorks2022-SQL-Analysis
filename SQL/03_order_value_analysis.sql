Analytical Focus:

    1. Examine the composition of high-value sales orders
    2. Investigate the relationship between order lines, quantity,
       unit price, and total order value
    3. Identify products contributing most to high-value orders
    4. Calculate product contribution percentages

Key Measures:

    Order-line value = OrderQty × UnitPrice
    Order value      = SUM(OrderQty × UnitPrice)

Important Analytical Distinction:

    02_relationship_analysis.sql
        Establishes how the core tables relate and demonstrates the
        movement from order-line grain to order grain.

    03_order_value_analysis.sql
        Builds on those relationships to investigate what contributes
        to high order value and how product value is distributed.

